#!/usr/bin/env python3
"""Build separate ELF64 app, canonical .tea, and embed verified ELF for isolated test.

All generated bytes stay under --output. No binary is committed or downloaded.
This boot-embedded fixture is NOT a runtime file-system/package loader.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import struct
import subprocess
import sys
from tea_package import pack, inspect

ROOT=Path(__file__).resolve().parents[1]
ORIGIN=0x10000000
SYMBOLS=('tea_768_start','tea_768_yield','tea_768_resume','tea_768_exit','tea_768_exit_resume')


def symbol_addresses(elf):
    blob=elf
    if len(blob)<64 or blob[:4]!=b'\x7fELF':raise ValueError('invalid ELF')
    shoff=struct.unpack_from('<Q',blob,40)[0]
    shentsize,shnum=struct.unpack_from('<HH',blob,58)
    if shentsize!=64 or not shnum or shoff>len(blob) or shnum*shentsize>len(blob)-shoff:
        raise ValueError('invalid ELF section table')
    sections=[struct.unpack_from('<IIQQQQIIQQ',blob,shoff+i*shentsize) for i in range(shnum)]
    result={}
    for sh in sections:
        typ,off,size,link,entsize=sh[1],sh[4],sh[5],sh[6],sh[9]
        if typ!=2: continue
        if link>=shnum or entsize!=24 or size%24 or off>len(blob) or size>len(blob)-off:
            raise ValueError('invalid symbol table')
        strsh=sections[link];str_off,str_size=strsh[4],strsh[5]
        if strsh[1]!=3 or str_off>len(blob) or str_size>len(blob)-str_off:
            raise ValueError('invalid symbol strings')
        stringtab=blob[str_off:str_off+str_size]
        for i in range(size//24):
            name,info,other,shndx,value,length=struct.unpack_from('<IBBHQQ',blob,off+24*i)
            if name>=len(stringtab):continue
            end=stringtab.find(b'\0',name)
            if end<0:continue
            name=stringtab[name:end].decode('ascii',errors='ignore')
            if name in SYMBOLS and shndx!=0:
                if name in result:raise ValueError('duplicate app symbol')
                result[name]=value
    if set(result)!=set(SYMBOLS):raise ValueError('missing native app symbols')
    if result['tea_768_start']!=ORIGIN:raise ValueError('entry mismatch')
    if not all(ORIGIN<=v<ORIGIN+4096 for v in result.values()):
        raise ValueError('out of page symbols')
    if not (result['tea_768_start']<result['tea_768_yield']<
            result['tea_768_resume']<result['tea_768_exit']<
            result['tea_768_exit_resume']):raise ValueError('invalid order')
    return {k:v-ORIGIN for k,v in result.items()}


def build(output):
    output.mkdir(parents=True,exist_ok=True)
    cc=shutil.which('clang')
    ld=shutil.which('ld.lld')
    if not cc or not ld: raise RuntimeError('clang and ld.lld required')
    obj,elf,package=(output/n for n in ('app.o','app.elf','minimal.tea'))
    subprocess.run([cc,'--target=x86_64-unknown-linux-gnu','-c','-nostdlib',
                    '-fno-pic',str(ROOT/'apps/tea_768_minimal.S'),'-o',str(obj)],check=True)
    subprocess.run([ld,'-nostdlib','--no-dynamic-linker','-z','max-page-size=0x1000',
                    '-T',str(ROOT/'apps/tea_768.ld'),'-o',str(elf),str(obj)],check=True)
    blob=elf.read_bytes()
    sites=symbol_addresses(blob)
    # Replace only our own deterministic generated artifact in the selected
    # output directory; never touch an arbitrary user-supplied .tea path.
    if package.exists():package.unlink()
    manifest=pack(package,elf,'styleos.probe','StyleOS CPL3 Probe','0.0.1','x86_64')
    assert inspect(package)==manifest
    with __import__('zipfile').ZipFile(package) as zipfile:
        assert zipfile.read('bin/x86_64/app.elf')==blob
    sha=hashlib.sha256(blob).digest()
    header=[f'/* Generated from canonical {package.name}; do not edit. */',
            f'#define TEA_768_ELF_SIZE {len(blob)}u',
            f'#define TEA_768_PKG_SHA "{hashlib.sha256(package.read_bytes()).hexdigest()}"',
            f'#define TEA_768_ELF_SHA "{sha.hex()}"']
    for name,off in sites.items():
        header.append('#define TEA_768_'+name.removeprefix('tea_768_').upper()+'_OFFSET '+str(off)+'u')
    header.extend(('static const unsigned char tea_768_elf[TEA_768_ELF_SIZE]={',
        ','.join('0x%02x'%b for b in blob)+'};',
        'static const unsigned char tea_768_sha256[32]={'+
        ','.join('0x%02x'%b for b in sha)+'};'))
    (output/'tea_768_payload.h').write_text('\n'.join(header)+'\n')
    report={'package_sha256':hashlib.sha256(package.read_bytes()).hexdigest(),
            'elf_sha256':sha.hex(),'elf_bytes':len(blob),'symbols':sites,
            'package_manifest':manifest,'format':'styleos.tea',
            'runtime_zip_parser':False,'boot_embedded_test_only':True}
    (output/'tea-768-site.json').write_text(json.dumps(report,indent=2)+'\n')
    print('NATIVE TEA 768 package verified:',package,'ELF SHA256',sha.hex())

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--output',type=Path,required=True)
    build(p.parse_args().output)
